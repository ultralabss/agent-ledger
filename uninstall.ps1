<#
.SYNOPSIS
  Removes what install.ps1 added: the scheduled task, the shims, hub.env, the user PATH entry and
  (if node is found) the Claude Code hook entries. The ledger is KEPT unless you pass -Purge.

.DESCRIPTION
  powershell -ExecutionPolicy Bypass -File .\uninstall.ps1 [-Purge] [-LedgerDir <path>]

  Only things this installer created are touched: the task must carry the installer's description,
  a shim must carry the generated marker, and the hook entries are the ones install-hooks.mjs wrote.
  -Purge additionally deletes the ledger directory (a git repository with your history) after you
  type `delete` to confirm; it is refused without a console, for a junction / symlink, for a drive
  root or your profile directory, and for a directory that does not look like a ledger.
#>
[CmdletBinding()]
param(
  [string]$LedgerDir,
  [string]$NodePath,
  [switch]$Purge
)

Set-StrictMode -Version 3.0
$ErrorActionPreference = 'Stop'

$TaskName = 'agent-ledger'
$TaskDescription = 'agent-ledger hub (started at logon by install.ps1)'
$ShimMarker = 'agent-ledger shim (generated by install.ps1)'
$Repo = $PSScriptRoot

function Fail([string]$Message) {
  Write-Error "uninstall: $Message"
  exit 1
}

if ($env:OS -ne 'Windows_NT') { Fail 'this script is for Windows; use uninstall.sh on macOS / Linux / WSL' }
$Identity = [Security.Principal.WindowsIdentity]::GetCurrent()
$Principal = New-Object Security.Principal.WindowsPrincipal($Identity)
if ($Principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
  Fail 'refusing to run elevated: open a normal PowerShell and run it again.'
}

function Test-Reparse([string]$Path) {
  return [bool]((Get-Item -LiteralPath $Path -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)
}

# --- scheduled task -----------------------------------------------------------------------------
$task = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
if ($task) {
  if ($task.Description -eq $TaskDescription) {
    Stop-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
    Write-Host "removed scheduled task: $TaskName"
  } else {
    Write-Host "left scheduled task '$TaskName' alone (it was not created by install.ps1)"
  }
} else {
  Write-Host 'no scheduled task to remove'
}

# --- shims, hub.env, data directory ---------------------------------------------------------------
$Local = [Environment]::GetFolderPath('LocalApplicationData')
$DataDir = Join-Path $Local 'agent-ledger'
$BinDir = Join-Path $DataDir 'bin'
if ((Test-Path -LiteralPath $DataDir) -and (Test-Reparse $DataDir)) {
  Write-Host "left $DataDir alone (it is a junction / symlink)"
} elseif (Test-Path -LiteralPath $DataDir) {
  foreach ($name in 'ledger.cmd', 'ledger.ps1', 'ledger') {
    $f = Join-Path $BinDir $name
    if (-not (Test-Path -LiteralPath $f)) { continue }
    if ((Test-Reparse $f) -or -not (Test-Path -LiteralPath $f -PathType Leaf)) { Write-Host "left $f alone (not a regular file)"; continue }
    $head = (Get-Content -LiteralPath $f -TotalCount 3 -ErrorAction SilentlyContinue) -join "`n"
    if ($head -like "*$ShimMarker*") { Remove-Item -LiteralPath $f -Force; Write-Host "removed shim: $f" }
    else { Write-Host "left $f alone (it was not generated by install.ps1)" }
  }
  $env_ = Join-Path $DataDir 'hub.env'
  if ((Test-Path -LiteralPath $env_ -PathType Leaf) -and -not (Test-Reparse $env_)) { Remove-Item -LiteralPath $env_ -Force; Write-Host "removed $env_" }
  # Directories only when empty: anything else in there is not ours to delete.
  foreach ($d in $BinDir, $DataDir) {
    if ((Test-Path -LiteralPath $d) -and -not (Test-Reparse $d) -and -not (Get-ChildItem -LiteralPath $d -Force)) {
      Remove-Item -LiteralPath $d -Force
    }
  }
}

# --- user PATH entry (exact match only) -----------------------------------------------------------
$key = [Microsoft.Win32.Registry]::CurrentUser.OpenSubKey('Environment', $true)
try {
  $cur = [string]$key.GetValue('Path', '', 'DoNotExpandEnvironmentNames')
  $parts = @($cur.Split(';') | Where-Object { $_ -ne '' })
  $kept = @($parts | Where-Object { $_.TrimEnd('\') -ine $BinDir.TrimEnd('\') })
  if ($kept.Count -ne $parts.Count) {
    $key.SetValue('Path', ($kept -join ';'), [Microsoft.Win32.RegistryValueKind]::ExpandString)
    Write-Host "removed $BinDir from your user PATH (open a new terminal)"
  }
} finally { $key.Close() }

# --- Claude Code hooks (non-fatal) ----------------------------------------------------------------
$Hooks = Join-Path $Repo 'adapters\claude-code\install-hooks.mjs'
$Node = $null
$cands = @()
if ($NodePath) { $cands += $NodePath } else {
  $cands += (Join-Path ([Environment]::GetFolderPath('ProgramFiles')) 'nodejs\node.exe')
  $cands += (Join-Path $Local 'Programs\nodejs\node.exe')
  $p = Get-Command node.exe -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
  if ($p) { $cands += $p.Source }
}
foreach ($c in $cands) { if ($c -match '^[A-Za-z]:\\' -and (Test-Path -LiteralPath $c -PathType Leaf)) { $Node = $c; break } }
if (-not $Node) {
  Write-Host 'hooks: node.exe not found - if you installed the Claude Code hooks, remove them with:'
  Write-Host "       node `"$Hooks`" --uninstall"
} elseif (-not (Test-Path -LiteralPath $Hooks -PathType Leaf)) {
  Write-Host "hooks: $Hooks not found - nothing to remove"
} else {
  Write-Host '==> Claude Code hooks (only entries written by install-hooks.mjs)'
  $hookArgs = @($Hooks, '--uninstall')
  if ([Console]::IsInputRedirected) { $hookArgs += '--yes' }
  & $Node @hookArgs
  if ($LASTEXITCODE -ne 0) { Write-Host "hooks: could not remove them (exit $LASTEXITCODE) - run by hand: node `"$Hooks`" --uninstall" }
}

# --- ledger: kept unless -Purge ---------------------------------------------------------------------
$Ledger = $LedgerDir
if (-not $Ledger) { $Ledger = $env:LEDGER_DIR }
if (-not $Ledger) { $Ledger = Join-Path ([Environment]::GetFolderPath('UserProfile')) '.ledger' }
if (-not $Purge) {
  Write-Host "ledger $Ledger left untouched (a git repository with its history); -Purge deletes it after confirmation"
  exit 0
}

$full = [IO.Path]::GetFullPath($Ledger).TrimEnd('\')
$profileDir = [Environment]::GetFolderPath('UserProfile').TrimEnd('\')
if ($full -notmatch '^[A-Za-z]:\\.+' -or $full -ieq $profileDir -or $full.Length -le 3) { Fail "refusing to purge $full" }
if (-not (Test-Path -LiteralPath $full -PathType Container)) { Write-Host "ledger $full does not exist - nothing to purge"; exit 0 }
if (Test-Reparse $full) { Fail "$full is a junction / symlink - refusing to purge" }
if (-not ((Test-Path -LiteralPath (Join-Path $full '.hub')) -or (Test-Path -LiteralPath (Join-Path $full '.git')))) {
  Fail "$full does not look like a ledger (no .hub or .git inside) - refusing to purge"
}
if ([Console]::IsInputRedirected) { Fail '-Purge needs an interactive console to confirm' }
Write-Host "This permanently deletes the ledger and its history: $full"
$answer = Read-Host 'Type "delete" to confirm'
if ($answer -ne 'delete') { Write-Host 'not confirmed - the ledger was kept'; exit 1 }
# A junction planted INSIDE the ledger must not be followed: walk it by hand, delete links as links.
function Remove-Tree([string]$Path) {
  foreach ($c in Get-ChildItem -LiteralPath $Path -Force) {
    $isDir = $c -is [IO.DirectoryInfo]
    if ($c.Attributes -band [IO.FileAttributes]::ReparsePoint) {
      if ($isDir) { [IO.Directory]::Delete($c.FullName) } else { [IO.File]::Delete($c.FullName) }
    } elseif ($isDir) {
      Remove-Tree $c.FullName
      [IO.Directory]::Delete($c.FullName)
    } else {
      [IO.File]::SetAttributes($c.FullName, [IO.FileAttributes]::Normal)
      [IO.File]::Delete($c.FullName)
    }
  }
}
Remove-Tree $full
[IO.Directory]::Delete($full)
Write-Host "purged $full"

/** B7 — `ledger setup` (the installer's node half) and the generated shims / hook launcher.
 *  The shim text is the security-relevant artefact (it is code that runs on every `ledger` call),
 *  so `ledger.cmd` is pinned byte for byte. PowerShell / icacls / Task Scheduler code paths are NOT
 *  exercised here (no Windows in this environment); platformTrust has its own fixture tests. */


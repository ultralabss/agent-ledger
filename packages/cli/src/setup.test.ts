const NODE = 'C:\\Program Files\\nodejs\\node.exe';
const BIN = 'C:\\Users\\Jane Doe\\src\\agent-ledger\\packages\\cli\\src\\bin.ts';

test('ledger.cmd golden: CRLF, delayed expansion off, one quoted exec line, args passed through', () => {
  assert.equal(
    renderCmdShim({ node: NODE, cliBin: BIN }),
    '@rem agent-ledger shim (generated by install.ps1)\r\n' +
      '@setlocal DisableDelayedExpansion\r\n' +
      '@"C:\\Program Files\\nodejs\\node.exe" "C:\\Users\\Jane Doe\\src\\agent-ledger\\packages\\cli\\src\\bin.ts" %*\r\n',
  );
});

test('ledger.cmd: paths that cmd.exe could treat specially are refused, never escaped', () => {
  const bad = [
    'C:\\100%\\node.exe', // %VAR% expansion
    'C:\\hi!\\node.exe', // delayed expansion
    'C:\\a"b\\node.exe', // ends the quoting
    'C:\\a\r\nb\\node.exe', // second batch line
    'C:\\a\u202eb\\node.exe', // bidi spoof
    'C:\\J\u00e1n\\node.exe', // non-ASCII: OEM code page would run a different path
    `C:\\${'a'.repeat(300)}\\node.exe`, // beyond MAX_PATH without longPaths
    '',
  ];
  for (const p of bad) {
    assert.throws(() => renderCmdShim({ node: p, cliBin: BIN }), RangeError, JSON.stringify(p));
    assert.throws(() => renderCmdShim({ node: NODE, cliBin: p }), RangeError, JSON.stringify(p));
  }
});

test('ledger.ps1: single-quoted literals, every PowerShell quote character doubled, exit code forwarded', () => {
  const text = renderPs1Shim({ node: NODE, cliBin: "C:\\it's\\\u2019x\\bin.ts" });
  assert.equal(
    text,
    `# ${SHIM_MARKER}\r\n& 'C:\\Program Files\\nodejs\\node.exe' 'C:\\it''s\\\u2019\u2019x\\bin.ts' @args\r\nexit $LASTEXITCODE\r\n`,
  );
});

test('ledger (Git Bash): forward slashes, single quotes escaped, LF', () => {
  const text = renderShShim({ node: NODE, cliBin: "C:\\it's\\bin.ts" });
  assert.equal(
    text,
    `#!/usr/bin/env bash\n# ${SHIM_MARKER}\nexec 'C:/Program Files/nodejs/node.exe' 'C:/it'\\''s/bin.ts' "$@"\n`,
  );
  assert.ok(!text.includes('\r'));
});

test('hub.env: literal KEY=value lines; values that dotenv would reinterpret are refused', () => {
  assert.equal(renderHubEnv({ LEDGER_DIR: 'C:\\Users\\Jane Doe\\.ledger', LEDGER_HUB_PORT: '4747' }), 'LEDGER_DIR=C:\\Users\\Jane Doe\\.ledger\nLEDGER_HUB_PORT=4747\n');
  for (const v of ['a"b', "a'b", 'a`b', 'a # b', 'a\nb=c', ' lead', 'trail ', '']) {
    assert.throws(() => renderHubEnv({ LEDGER_DIR: v }), RangeError, JSON.stringify(v));
  }
  assert.throws(() => renderHubEnv({ 'lower': 'x' }), RangeError);
  assert.throws(() => renderHubEnv({ 'A=B': 'x' }), RangeError);
});

test('task arguments: one CRT-quoted string that parses back to the three arguments', () => {
  const args = hubTaskArguments({ envFile: 'C:\\Users\\Jane Doe\\AppData\\Local\\agent-ledger\\hub.env', hubBin: 'C:\\src\\hub dir\\bin.ts' });
  assert.equal(
    args,
    '"--env-file=C:\\Users\\Jane Doe\\AppData\\Local\\agent-ledger\\hub.env" --disable-warning=ExperimentalWarning "C:\\src\\hub dir\\bin.ts"',
  );
  assert.throws(() => hubTaskArguments({ envFile: 'C:\\a%b\\hub.env', hubBin: 'C:\\x\\bin.ts' }), RangeError);
});

test('Claude hook launcher (win32): node.exe + bin.ts, forward slashes, never a .cmd, shell metacharacters refused', () => {
  const l = winHookLauncher({ node: NODE, cliBin: BIN });
  assert.equal(l, '"C:/Program Files/nodejs/node.exe" "C:/Users/Jane Doe/src/agent-ledger/packages/cli/src/bin.ts"');
  assert.ok(!/\.(cmd|bat|ps1)\b/i.test(l));
  assert.throws(() => winHookLauncher({ node: 'C:\\a$HOME\\node.exe', cliBin: BIN }), RangeError);
  assert.throws(() => winHookLauncher({ node: NODE, cliBin: 'C:\\a`id`\\bin.ts' }), RangeError);
  assert.throws(() => winHookLauncher({ node: 'C:\\a%PATH%\\node.exe', cliBin: BIN }), RangeError);
});

test('findWinHookLaunchers: finds our entries behind a moved node.exe, ignores foreign ones', () => {
  const old = '"C:/old/node.exe" "C:/Users/Jane Doe/src/agent-ledger/packages/cli/src/bin.ts"';
  const settings = {
    hooks: {
      Stop: [
        { hooks: [{ command: `${old} hook stop` }, { command: 'C:/tools/other.exe hook stop' }] },
        { hooks: [{ command: '"C:/x/node.exe" "C:/elsewhere/bin.ts" hook stop' }] },
      ],
    },
  };
  assert.deepEqual(findWinHookLaunchers(settings, BIN, ['stop', 'session-start']), [old]);
  assert.deepEqual(findWinHookLaunchers({}, BIN, ['stop']), []);
  assert.deepEqual(findWinHookLaunchers(null, BIN, ['stop']), []);
});


// ---- cmdSetup against a real (POSIX) filesystem; the node trust check is seamed -----------------

interface Run {
  code: number;
  out: string[];
  err: string[];
}

async function setup(argv: string[], root: string, deps: Partial<SetupDeps> = {}, env: NodeJS.ProcessEnv = {}): Promise<Run> {
  const out: string[] = [];
  const err: string[] = [];
  const code = await cmdSetup(
    parseArgs(['setup', ...argv].slice(1)),
    { out: (l) => out.push(l), err: (l) => err.push(l), env, cwd: root },
    { homedir: () => root, checkNode: async () => null, ...deps },
  );
  return { code, out, err };
}

async function sandbox(t: { after: (fn: () => Promise<void>) => void }): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), 'ledger-setup-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  return root;
}

test('platform-init: private dirs, hub.env, three shims, JSON for the installer; re-run is idempotent', { skip: skipOnWin32('POSIX modes') }, async (t) => {
  const root = await sandbox(t);
  const argv = ['--platform-init', '--ledger-dir', join(root, 'led ger'), '--data-dir', join(root, 'data'), '--port', '5001'];
  const env = { LEDGER_PUSH: '1', UNRELATED: 'x' };
  const first = await setup(argv, root, {}, env);
  assert.equal(first.code, 0, first.err.join('\n'));
  const info = JSON.parse(first.out.at(-1) ?? '{}');
  assert.equal(info.ok, true);
  assert.equal(info.port, 5001);
  assert.deepEqual(info.shims, { cmd: 'written', ps1: 'written', sh: 'written' });
  assert.match(info.taskArguments, /--env-file=.*hub\.env/);

  for (const d of [info.ledgerDir, join(info.ledgerDir, '.hub'), join(info.ledgerDir, '.hub', 'bin'), info.dataDir, info.binDir]) {
    assert.equal((await stat(d)).mode & 0o777, 0o700, d);
  }
  assert.equal(
    await readFile(info.hubEnv, 'utf8'),
    `LEDGER_DIR=${info.ledgerDir}\nLEDGER_HUB_PORT=5001\nLEDGER_PUSH=1\n`,
    'only known flags are passed through',
  );
  assert.equal((await stat(info.hubEnv)).mode & 0o777, 0o600);
  assert.ok((await readFile(join(info.binDir, 'ledger.cmd'), 'utf8')).includes('\r\n@setlocal DisableDelayedExpansion\r\n'));
  assert.ok((await readFile(join(info.binDir, 'ledger.ps1'), 'utf8')).startsWith(`\ufeff# ${SHIM_MARKER}`));
  assert.equal((await readdir(info.binDir)).filter((n) => n.endsWith('.tmp')).length, 0, 'no temp files left behind');

  const again = await setup(argv, root, {}, env);
  assert.equal(again.code, 0, again.err.join('\n'));
  assert.deepEqual(JSON.parse(again.out.at(-1) ?? '{}').shims, { cmd: 'unchanged', ps1: 'unchanged', sh: 'unchanged' });
});

test('platform-init: a file that is not one of our shims is never overwritten', { skip: skipOnWin32('POSIX modes') }, async (t) => {
  const root = await sandbox(t);
  const bin = join(root, 'data', 'bin');
  const argv = ['--platform-init', '--ledger-dir', join(root, 'led'), '--data-dir', join(root, 'data')];
  assert.equal((await setup(argv, root)).code, 0);
  await writeFile(join(bin, 'ledger.cmd'), '@echo someone else wrote this\r\n');
  const r = await setup(argv, root);
  assert.equal(r.code, 0, r.err.join('\n'));
  assert.equal(JSON.parse(r.out.at(-1) ?? '{}').shims.cmd, 'left alone (not generated by install.ps1)');
  assert.equal(await readFile(join(bin, 'ledger.cmd'), 'utf8'), '@echo someone else wrote this\r\n');
});

test('platform-init: node too old -> 4, untrusted node -> 1, nothing is created either way', async (t) => {
  const root = await sandbox(t);
  const argv = ['--platform-init', '--ledger-dir', join(root, 'led'), '--data-dir', join(root, 'data')];
  const old = await setup(argv, root, { nodeVersion: '22.17.0' });
  assert.equal(old.code, 4);
  assert.match(old.err.join('\n'), /too old/);
  const planted = await setup(argv, root, { checkNode: async () => 'writable by someone else' });
  assert.equal(planted.code, 1);
  assert.match(planted.err.join('\n'), /not in a trusted location/);
  await assert.rejects(stat(join(root, 'led')));
  await assert.rejects(stat(join(root, 'data')));
});

test('platform-init: bad port / relative dir -> 4; symlinked ledger dir is refused (1)', { skip: skipOnWin32('symlinks') }, async (t) => {
  const root = await sandbox(t);
  assert.equal((await setup(['--platform-init', '--port', '70000', '--ledger-dir', join(root, 'l')], root)).code, 4);
  assert.equal((await setup(['--platform-init', '--ledger-dir', 'relative/dir'], root)).code, 4);
  const real = join(root, 'real');
  await mkdir(real, { mode: 0o700 });
  await symlink(real, join(root, 'link'));
  const r = await setup(['--platform-init', '--ledger-dir', join(root, 'link'), '--data-dir', join(root, 'data')], root);
  assert.equal(r.code, 1, r.err.join('\n'));
  assert.match(r.err.join('\n'), /refused \(SYMLINK\)/);
});

test('private-dir: creates a fresh private directory, refuses one that already exists', { skip: skipOnWin32('POSIX modes') }, async (t) => {
  const root = await sandbox(t);
  const dir = join(root, 'scratch');
  const ok = await setup(['--private-dir', dir], root);
  assert.equal(ok.code, 0, ok.err.join('\n'));
  assert.equal(ok.out[0], dir);
  assert.equal((await stat(dir)).mode & 0o777, 0o700);
  assert.equal((await setup(['--private-dir', dir], root)).code, 1);
});

test('place-gitleaks: copy + sha256 + origin side-cars next to it, old copy replaced', { skip: skipOnWin32('POSIX modes') }, async (t) => {
  const root = await sandbox(t);
  const ledger = join(root, 'led');
  assert.equal((await setup(['--platform-init', '--ledger-dir', ledger, '--data-dir', join(root, 'data')], root)).code, 0);
  const src = join(root, 'gitleaks-src');
  const bytes = Buffer.from('MZ not really an exe');
  await writeFile(src, bytes);
  await chmod(src, 0o600);
  for (let i = 0; i < 2; i += 1) {
    const r = await setup(['--place-gitleaks', src, '--ledger-dir', ledger], root);
    assert.equal(r.code, 0, r.err.join('\n'));
    const info = JSON.parse(r.out.at(-1) ?? '{}');
    assert.equal(info.sha256, createHash('sha256').update(bytes).digest('hex'));
    assert.deepEqual(await readFile(info.path), bytes);
    assert.equal((await readFile(`${info.path}.sha256`, 'utf8')).trim(), info.sha256);
    assert.match(await readFile(`${info.path}.origin`, 'utf8'), /^upstream v\d+\.\d+\.\d+ \(sha256 verified against the in-repo pin/);
  }
  const link = join(root, 'src-link');
  await symlink(src, link);
  assert.equal((await setup(['--place-gitleaks', link, '--ledger-dir', ledger], root)).code, 1, 'a symlink source is refused');
});


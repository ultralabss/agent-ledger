#!/usr/bin/env bash
# Removes the Agent Ledger service (launchd agent / systemd user unit) and the
# `ledger` shim, and (when node is available) the Claude Code hook entries that
# adapters/claude-code/install-hooks.mjs added to ~/.claude/settings.json. Only
# entries that adapter wrote are removed. The ledger data is NEVER touched.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

LABEL="${AGENT_LEDGER_LABEL:-io.agent-ledger.hub}"
LEDGER="${LEDGER_DIR:-$HOME/.ledger}"
SHIM="${SHIM_DIR:-$HOME/.local/bin}/ledger"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
UNIT="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user/$LABEL.service"

if [[ ! "$LABEL" =~ ^[A-Za-z0-9._-]+$ ]]; then
  echo "uninstall: AGENT_LEDGER_LABEL may only contain letters, digits, '.', '_' and '-'" >&2
  exit 1
fi

case "$(uname -s)" in
  Darwin)
    launchctl bootout "gui/$UID/$LABEL" 2>/dev/null || true
    rm -f "$PLIST"
    echo "removed launchd agent: $LABEL"
    ;;
  Linux)
    if command -v systemctl >/dev/null 2>&1; then
      systemctl --user disable --now "$LABEL.service" 2>/dev/null || true
    fi
    rm -f "$UNIT"
    if command -v systemctl >/dev/null 2>&1; then
      systemctl --user daemon-reload 2>/dev/null || true
    fi
    echo "removed systemd user unit: $LABEL.service"
    ;;
  *)
    echo "no service support on this OS — nothing to stop"
    ;;
esac

# Only remove a shim that install.sh generated; never a file someone else put there.
if [[ -f "$SHIM" ]] && grep -q '^# agent-ledger shim' "$SHIM" 2>/dev/null; then
  rm -f "$SHIM"
  echo "removed shim: $SHIM"
elif [[ -e "$SHIM" ]]; then
  echo "left $SHIM alone (it was not generated by install.sh)"
fi

# Claude Code hooks. Non-fatal: a failure here must not hide that the service is
# already gone, and an agent that is not installed has nothing to remove.
HOOKS="$REPO/adapters/claude-code/install-hooks.mjs"
NODE="$(command -v node || true)"
if [[ -z "$NODE" ]]; then
  echo "hooks: node not found — if you installed the Claude Code hooks, remove them with:"
  echo "       node $HOOKS --uninstall"
elif [[ ! -f "$HOOKS" ]]; then
  echo "hooks: $HOOKS not found — nothing to remove"
else
  echo "==> Claude Code hooks (only entries written by install-hooks.mjs)"
  # Interactive: the script asks for confirmation itself. Non-interactive
  # (an agent running this script): running uninstall.sh is the consent.
  hook_args=(--uninstall --ledger "$SHIM")
  [[ -t 0 ]] || hook_args+=(--yes)
  if "$NODE" "$HOOKS" "${hook_args[@]}"; then
    echo "hooks: done"
  else
    echo "hooks: could not remove them (exit $?) — run by hand: node $HOOKS --uninstall" >&2
  fi
fi

echo "ledger $LEDGER left untouched (a git repository with its history)"
